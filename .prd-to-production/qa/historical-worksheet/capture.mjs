import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { chromium } = require(path.resolve('tests/e2e/node_modules/@playwright/test'));
const out = path.resolve('.prd-to-production/qa/historical-worksheet');
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [];
page.on('pageerror', error => errors.push(String(error)));
await page.goto('http://127.0.0.1:8096/?run=r_20261017_182916_abc3#report');
await page.getByRole('button', { name: 'Generate worksheet', exact: true }).click();
await page.getByRole('article', { name: 'Historical IRS worksheet — 2012 reference' }).waitFor();
await page.evaluate(() => document.fonts.ready);
await page.screenshot({ path: path.join(out, 'desktop.png') });
await page.setViewportSize({ width: 390, height: 844 });
await page.screenshot({ path: path.join(out, 'mobile.png') });
await page.setViewportSize({ width: 1440, height: 1000 });
const annex = page.locator('.irs-evidence-annex');
await annex.scrollIntoViewIfNeeded();
await page.screenshot({ path: path.join(out, 'evidence-annex.png') });
await page.evaluate(() => { window.print = () => { window.__printedForCapture = true; }; });
await page.getByRole('button', { name: 'Print / Save as PDF', exact: true }).click();
await page.locator('body.irs-print-verified').waitFor();
await page.pdf({ path: path.resolve('output/pdf/historical-irs-worksheet.pdf'), format: 'A4', preferCSSPageSize: true, printBackground: true });
const summary = { run: 'r_20261017_182916_abc3', questions: await page.locator('.irs-question').count(), blankAnswers: await page.locator('.irs-answer').evaluateAll(nodes => nodes.filter(n => n.textContent === '').length), errors };
fs.writeFileSync(path.join(out, 'real-run-capture.json'), JSON.stringify(summary, null, 2) + '\n');
console.log(JSON.stringify(summary));
await browser.close();
